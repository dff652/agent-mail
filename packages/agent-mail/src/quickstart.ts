/**
 * TypeScript project quickstart: init + pasteable MCP configs for one agent
 * (default) or a small set of runners. No model calls, no network.
 */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { AgentMailError } from "./errors.js";
import * as svc from "./services.js";

export const DEFAULT_RUNNERS = ["codex"] as const;
export const ALL_RUNNERS = ["codex", "claude", "grok"] as const;

export const RUNNER_AGENT: Record<string, string> = {
  codex: "codex@local",
  claude: "claude-code@local",
  grok: "grok@local",
};

const RUNNER_INSTALL_HINT: Record<string, string> = {
  claude: "https://docs.anthropic.com/en/docs/claude-code",
  codex: "https://github.com/openai/codex",
  grok: "Install Grok CLI and ensure `grok` is on PATH",
};

export type QuickstartResult = {
  project: string;
  home: string;
  node: string;
  mcp_command: string;
  mcp_args: string[];
  wrote: string[];
  skipped: string[];
  notes: string[];
  runners_found: Record<string, string | null>;
  /** Relative paths of MCP config files written or already present. */
  configs: string[];
};

function which(bin: string): string | null {
  const r = spawnSync("sh", ["-c", `command -v ${JSON.stringify(bin)}`], {
    encoding: "utf8",
  });
  if (r.status !== 0) return null;
  const line = (r.stdout || "").trim().split("\n")[0];
  return line || null;
}

/** Prefer `node /…/dist/mcp/stdio.js` so install layout does not require global bin. */
export function resolveMcpInvocation(): { command: string; args: string[] } {
  const here = path.dirname(fileURLToPath(import.meta.url));
  const candidates = [
    path.join(here, "mcp", "stdio.js"),
    path.join(here, "..", "dist", "mcp", "stdio.js"),
  ];
  for (const script of candidates) {
    if (fs.existsSync(script)) {
      return { command: process.execPath, args: [path.resolve(script)] };
    }
  }
  const bin = which("agent-mail-mcp");
  if (bin) return { command: bin, args: [] };
  throw new AgentMailError(
    "cannot locate agent-mail-mcp; build the package or install agent-mail",
    3,
  );
}

export function parseRunners(value: string | string[] | null | undefined): string[] {
  if (value == null || value === "") return [...DEFAULT_RUNNERS];
  const parts = Array.isArray(value)
    ? value.map((p) => String(p).trim().toLowerCase()).filter(Boolean)
    : value
        .replace(/;/g, ",")
        .split(",")
        .map((p) => p.trim().toLowerCase())
        .filter(Boolean);
  const out: string[] = [];
  for (const p of parts) {
    if (!(p in RUNNER_AGENT)) {
      throw new AgentMailError(
        `unknown runner ${JSON.stringify(p)}; choose from ${ALL_RUNNERS.join(",")}`,
        2,
      );
    }
    if (!out.includes(p)) out.push(p);
  }
  return out.length ? out : [...DEFAULT_RUNNERS];
}

function writeText(filePath: string, content: string, force: boolean): "wrote" | "skipped" {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  if (fs.existsSync(filePath) && !force) return "skipped";
  fs.writeFileSync(filePath, content, "utf8");
  return "wrote";
}

function claudeMcpJson(
  command: string,
  args: string[],
  home: string,
  agentId: string,
): string {
  return (
    JSON.stringify(
      {
        mcpServers: {
          "agent-mail": {
            command,
            args,
            env: {
              AGENT_MAIL_HOME: home,
              AGENT_MAIL_ID: agentId,
            },
          },
        },
      },
      null,
      2,
    ) + "\n"
  );
}

function codexToml(
  command: string,
  args: string[],
  project: string,
  home: string,
  agentId: string,
): string {
  const argLines = args.map((a) => `  ${JSON.stringify(a)},`).join("\n");
  return (
    `# Generated by agent-mail quickstart (TypeScript)\n` +
    `[mcp_servers.agent-mail]\n` +
    `command = ${JSON.stringify(command)}\n` +
    `args = [\n${argLines}\n]\n` +
    `cwd = ${JSON.stringify(project)}\n` +
    `required = true\n` +
    `startup_timeout_sec = 20\n` +
    `tool_timeout_sec = 120\n` +
    `\n` +
    `[mcp_servers.agent-mail.env]\n` +
    `AGENT_MAIL_HOME = ${JSON.stringify(home)}\n` +
    `AGENT_MAIL_ID = ${JSON.stringify(agentId)}\n`
  );
}

function grokToml(
  command: string,
  args: string[],
  home: string,
  agentId: string,
): string {
  const argLines = args.map((a) => `  ${JSON.stringify(a)},`).join("\n");
  return (
    `# Generated by agent-mail quickstart (TypeScript)\n` +
    `[mcp_servers.agent-mail]\n` +
    `command = ${JSON.stringify(command)}\n` +
    `args = [\n${argLines}\n]\n` +
    `enabled = true\n` +
    `\n` +
    `[mcp_servers.agent-mail.env]\n` +
    `AGENT_MAIL_HOME = ${JSON.stringify(home)}\n` +
    `AGENT_MAIL_ID = ${JSON.stringify(agentId)}\n`
  );
}

export type RunQuickstartOptions = {
  runners?: string[] | null;
  force?: boolean;
  skipDoctor?: boolean;
};

export function runQuickstart(
  projectPath: string,
  options: RunQuickstartOptions = {},
): QuickstartResult {
  const project = path.resolve(projectPath);
  fs.mkdirSync(project, { recursive: true });
  const home = path.join(project, ".agent-mail");
  svc.initProject(home);

  const selected = options.runners ?? [...DEFAULT_RUNNERS];
  const force = options.force === true;
  const mcp = resolveMcpInvocation();

  const result: QuickstartResult = {
    project,
    home,
    node: process.execPath,
    mcp_command: mcp.command,
    mcp_args: mcp.args,
    wrote: [],
    skipped: [],
    notes: [],
    runners_found: {},
    configs: [],
  };

  for (const runner of selected) {
    const agentId = RUNNER_AGENT[runner]!;
    const binName = runner === "claude" ? "claude" : runner;
    const found = which(binName);
    result.runners_found[runner] = found;
    if (!found) {
      result.notes.push(
        `${runner}: CLI not on PATH — install: ${RUNNER_INSTALL_HINT[runner]}`,
      );
    }

    let rel: string;
    let content: string;
    if (runner === "claude") {
      rel = ".mcp.json";
      content = claudeMcpJson(mcp.command, mcp.args, home, agentId);
    } else if (runner === "codex") {
      rel = path.join(".codex", "config.toml");
      content = codexToml(mcp.command, mcp.args, project, home, agentId);
    } else {
      rel = path.join(".grok", "config.toml");
      content = grokToml(mcp.command, mcp.args, home, agentId);
    }

    const abs = path.join(project, rel);
    const status = writeText(abs, content, force);
    result.configs.push(rel);
    if (status === "wrote") result.wrote.push(rel);
    else result.skipped.push(`${rel} (exists; use --force to overwrite)`);
  }

  result.notes.push(
    `MCP uses ${mcp.command}${mcp.args.length ? " " + mcp.args.join(" ") : ""} — same Node that can import agent-mail`,
  );
  result.notes.push(
    "Same AGENT_MAIL_HOME for all tools (L1). See examples/mcp/ and docs/guides/INSTALL.md",
  );
  if (selected.length === 1) {
    result.notes.push(
      "Single-agent default: add more with --runners codex,claude,grok",
    );
  }

  if (!options.skipDoctor) {
    const configPath = path.join(home, "config.json");
    const agentsPath = path.join(home, "agents.json");
    if (fs.existsSync(configPath) && fs.existsSync(agentsPath)) {
      result.notes.push(
        "doctor: home initialized (run agent-mail doctor --deep for full checks)",
      );
    } else {
      result.notes.push("doctor: incomplete home — run agent-mail doctor");
    }
  }

  return result;
}

export function formatQuickstartHuman(result: QuickstartResult): string {
  const lines: string[] = [
    "Agent Mail quickstart (TypeScript)",
    `  project: ${result.project}`,
    `  home:    ${result.home}`,
    `  node:    ${result.node}`,
    `  mcp:     ${result.mcp_command}${result.mcp_args.length ? " " + result.mcp_args.map((a) => JSON.stringify(a)).join(" ") : ""}`,
  ];
  if (result.wrote.length) {
    lines.push("  wrote:");
    for (const w of result.wrote) lines.push(`    + ${w}`);
  }
  if (result.skipped.length) {
    lines.push("  skipped:");
    for (const s of result.skipped) lines.push(`    · ${s}`);
  }
  lines.push("  runners:");
  for (const [name, found] of Object.entries(result.runners_found)) {
    lines.push(`    ${name}: ${found ?? "NOT on PATH"}`);
  }
  for (const note of result.notes) lines.push(`  note: ${note}`);
  lines.push("");
  lines.push("Next:");
  lines.push("  agent-mail doctor --deep");
  lines.push("  # open this project in your agent so MCP loads");
  const first = Object.keys(result.runners_found)[0] ?? "codex";
  const id = RUNNER_AGENT[first] ?? "codex@local";
  lines.push(
    `  agent-mail send --as ${id} --to ${id} --type message --body "hello from quickstart"`,
  );
  lines.push("Docs: docs/guides/INSTALL.md · examples/mcp/ · docs/product/demo-60s-script.md");
  return lines.join("\n");
}
